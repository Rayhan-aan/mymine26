/* ---------- Musik ---------- */
const Music = (() => {
  const VOL = (CONFIG.music && CONFIG.music.volume) || .5;
  const btn = $("#music");
  let ctx, master, bus, timer, el, fe;
  let nextT = 0, step = 0, mel = 2, started = false, muted = false, ducked = false;
  const EIGHTH = 60 / 64 / 2;                       // tempo pelan (64 bpm)
  const CH  = [[48,52,55,59],[45,52,55,60],[41,48,52,57],[43,50,55,59]];   // C, Am, F, G
  const PAD = [[36,43,52],[33,40,48],[29,36,45],[31,38,47]];
  const ARP = [0,2,1,3,2,3,1,2];
  const PENT = [72,74,76,79,81,84];
  const hz = m => 440 * Math.pow(2, (m - 69) / 12);
  const level = () => muted ? 0 : ducked ? VOL * .08 : VOL;

  function note(m, t, dur, g) {
    const o = ctx.createOscillator(), o2 = ctx.createOscillator(), b = ctx.createGain(), a = ctx.createGain(), f = ctx.createBiquadFilter();
    o.type = "triangle"; o2.type = "sine";
    o.frequency.value = hz(m); o2.frequency.value = hz(m) * 2;
    f.type = "lowpass"; f.frequency.value = 2600; b.gain.value = .25;
    a.gain.setValueAtTime(.0001, t);
    a.gain.exponentialRampToValueAtTime(g, t + .012);
    a.gain.exponentialRampToValueAtTime(.0001, t + dur);
    o.connect(f); o2.connect(b); b.connect(f); f.connect(a); a.connect(bus);
    o.start(t); o2.start(t); o.stop(t + dur + .05); o2.stop(t + dur + .05);
  }
  function pad(ms, t, dur) {
    ms.forEach(m => {
      const o = ctx.createOscillator(), a = ctx.createGain();
      o.type = "sine"; o.frequency.value = hz(m);
      a.gain.setValueAtTime(.0001, t);
      a.gain.linearRampToValueAtTime(.05, t + 1.4);
      a.gain.linearRampToValueAtTime(.0001, t + dur);
      o.connect(a); a.connect(bus); o.start(t); o.stop(t + dur + .1);
    });
  }
  function impulse(sec, decay) {
    const n = Math.floor(ctx.sampleRate * sec), buf = ctx.createBuffer(2, n, ctx.sampleRate);
    for (let c = 0; c < 2; c++) { const d = buf.getChannelData(c); for (let i = 0; i < n; i++) d[i] = (Math.random() * 2 - 1) * Math.pow(1 - i / n, decay); }
    return buf;
  }
  function playStep(s, t) {
    const bar = Math.floor(s / 8) % 4, pos = s % 8, ch = CH[bar];
    if (pos === 0) { pad(PAD[bar], t, 8 * EIGHTH + 1.6); note(ch[0] - 12, t, 3.2, .2); }
    if (pos === 4) note(ch[0] - 12, t, 2.2, .12);
    note(ch[ARP[pos]], t, 1.7, .15);
    if (pos === 0 || ((pos === 3 || pos === 6) && Math.random() < .7)) {
      mel = Math.max(0, Math.min(PENT.length - 1, mel + [-2, -1, -1, 1, 1, 2][Math.random() * 6 | 0]));
      note(PENT[mel], t, 2.4, .12);
    }
  }
  function tick() { while (nextT < ctx.currentTime + .35) { playStep(step++, nextT); nextT += EIGHTH; } }

  function fadeEl() {
    clearInterval(fe);
    fe = setInterval(() => {
      if (!el) return clearInterval(fe);
      const t = level(), d = t - el.volume;
      if (Math.abs(d) < .01) { el.volume = t; clearInterval(fe); }
      else el.volume = Math.max(0, Math.min(1, el.volume + d * .12));
    }, 50);
  }
  function apply(tc) {
    if (ctx) master.gain.setTargetAtTime(level(), ctx.currentTime, tc || .5);
    if (el) fadeEl();
  }
  function startSynth() {
    if (ctx) return;
    const AC = window.AudioContext || window.webkitAudioContext; if (!AC) return;
    ctx = new AC();
    master = ctx.createGain(); master.gain.value = 0; master.connect(ctx.destination);
    bus = ctx.createGain(); bus.connect(master);
    const conv = ctx.createConvolver(), wet = ctx.createGain();
    conv.buffer = impulse(3, 2.5); wet.gain.value = .5;
    bus.connect(conv); conv.connect(wet); wet.connect(master);
    if (ctx.resume) ctx.resume();
    nextT = ctx.currentTime + .15;
    tick(); timer = setInterval(tick, 120);
    apply(1.6);                                       // masuk pelan-pelan
  }
  function start() {
    if (started) return; started = true;
    try { if (navigator.audioSession) navigator.audioSession.type = "playback"; } catch (e) {}
    const src = CONFIG.music && CONFIG.music.src;
    if (src) {
      el = new Audio(src); el.loop = true; el.volume = 0;
      const fallback = () => { el = null; startSynth(); };
      el.addEventListener("error", fallback);
      el.play().then(fadeEl).catch(fallback);
    } else startSynth();
  }
  function toggle() {
    if (!started) { start(); return; }
    muted = !muted;
    btn.classList.toggle("on", !muted);
    btn.setAttribute("aria-pressed", String(!muted));
    btn.setAttribute("aria-label", muted ? "Nyalakan musik" : "Matikan musik");
    if (!muted) { if (ctx && ctx.resume) ctx.resume(); if (el && el.paused) el.play().catch(() => {}); }
    apply(.4);
    if (muted) setTimeout(() => { if (!muted) return; if (ctx && ctx.suspend) ctx.suspend(); if (el) el.pause(); }, 1600);
  }
  btn.addEventListener("click", toggle);

  /* hemat baterai: berhenti saat tab ditutup / pindah */
  document.addEventListener("visibilitychange", () => {
    if (!started) return;
    if (document.hidden) { if (ctx && ctx.suspend) ctx.suspend(); if (el) el.pause(); }
    else if (!muted) { if (ctx && ctx.resume) ctx.resume(); if (el) el.play().catch(() => {}); }
  });
  /* saat video diputar, musik mengecil otomatis */
  const checkDuck = () => {
    const playing = [...document.querySelectorAll("video")].some(v => !v.paused && !v.ended);
    if (playing !== ducked) { ducked = playing; apply(.4); }
  };
  ["play", "pause", "ended"].forEach(ev =>
    document.addEventListener(ev, e => { if (e.target instanceof HTMLVideoElement) setTimeout(checkDuck, 60); }, true));

  return { start, checkDuck };
})();

